DROP TABLE IF EXISTS recipes;
CREATE TABLE recipes (
    id SERIAL PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    ingredients TEXT NOT NULL,
    preparation TEXT NOT NULL,
    embedding BLOB,
    meal_type INTEGER CHECK (meal_type >= 1 AND meal_type <= 3),
    main_ingredient VARCHAR(255),
    nationality VARCHAR(100),
    vegetarian BOOLEAN DEFAULT FALSE,
    vegan BOOLEAN DEFAULT FALSE,
    gluten_free BOOLEAN DEFAULT FALSE,
    dairy_free BOOLEAN DEFAULT FALSE,
    nut_free BOOLEAN DEFAULT FALSE,
    high_fiber BOOLEAN DEFAULT FALSE,
    weight_loss_diet BOOLEAN DEFAULT FALSE,
    muscle_gain_bulking BOOLEAN DEFAULT FALSE,
    balanced_healthy BOOLEAN DEFAULT FALSE,
    carb_score FLOAT DEFAULT 0,
    protein_score FLOAT DEFAULT 0,
    fat_score FLOAT DEFAULT 0,
    calorie_score FLOAT DEFAULT 0,
    sugar_score FLOAT DEFAULT 0,
    preparation_time_score FLOAT DEFAULT 0,
    preparation_difficulty_score FLOAT DEFAULT 0,
    meal_class TEXT CHECK (
        meal_class IN (
            'Pasta',
            'Pizza',
            'Rice dish',
            'Noodle',
            'Burger',
            'Sandwich',
            'Wrap',
            'Taco',
            'Kebab',
            'Steak',
            'Grilled meat',
            'Fried chicken',
            'Seafood',
            'Curry',
            'Stew',
            'Casserole',
            'Salad',
            'Soup',
            'Bowl',
            'Fries',
            'Potato dish',
            'Bread',
            'Egg dish',
            'Pancake / waffle',
            'Dumplings',
            'Rolls',
            'Finger food',
            'Pastry',
            'Cake',
            'Cookie',
            'Ice cream',
            'Syrup dessert',
            'Coffee',
            'Tea',
            'Soft drink',
            'Smoothie / shake'
        )
    )
);